function isPlainObject(value: unknown): value is UnknownRecord {
  return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

function mergeValue(base: unknown, override: unknown): unknown {
  if (override === undefined) return base;
  if (Array.isArray(base) && Array.isArray(override)) {
    return override.map((item, index) => mergeValue(base[index], item));
  }
  if (isPlainObject(base) && isPlainObject(override)) {
    const merged: UnknownRecord = { ...base };
    for (const [key, value] of Object.entries(override)) {
      merged[key] = mergeValue(merged[key], value);
    }
    return merged;
  }
  return override;
}

export function isRussianLocale(locale: string): locale is "ru" {
  return locale === "ru";
}

export function mergeRussianContent<T>(locale: string, key: string, fallback: T): T {
  if (!isRussianLocale(locale)) return fallback;
  return mergeValue(fallback, RUSSIAN_PAGE_CONTENT[key as keyof typeof RUSSIAN_PAGE_CONTENT]) as T;
}

export function getRussianCampaignContent(slug: string, fallback: CampaignPageContent | null): CampaignPageContent | null {
  if (!fallback) return null;
  const key = `sales landing/${slug}` as keyof typeof RUSSIAN_PAGE_CONTENT;
  const russian = RUSSIAN_PAGE_CONTENT[key];
  if (!russian) return fallback;
  return mergeValue(fallback, russian) as CampaignPageContent;
}

export function getRussianLegalRows(slug: keyof typeof RUSSIAN_PROFESSIONAL_LEGAL_CONTENT) {
  return RUSSIAN_PROFESSIONAL_LEGAL_CONTENT[slug] ?? [];
}

export function getRussianInlineText(key: string, fallback: string): string {
  const value = key.split(".").reduce<unknown>((current, part) => {
    if (isPlainObject(current)) return current[part];
    return undefined;
  }, RUSSIAN_PAGE_CONTENT["shared inline UI"]);
  return typeof value === "string" ? value : fallback;
}
